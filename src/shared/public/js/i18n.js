export class I18nManager {
  constructor() {
    this.supported = ['es', 'en', 'ru', 'zh'];
    this.currentLang = this.detectInitialLanguage();
    this.listeners = [];
  }

  detectInitialLanguage() {
    const params = new URLSearchParams(window.location.search);
    const urlLang = (params.get('lang') || '').toLowerCase();
    if (this.supported.includes(urlLang)) {
      return urlLang;
    }

    const saved = (localStorage.getItem('vartool_lang') || '').toLowerCase();
    if (this.supported.includes(saved)) {
      return saved;
    }

    const navLang = (navigator.language || 'es').slice(0, 2).toLowerCase();
    return this.supported.includes(navLang) ? navLang : 'es';
  }

  t(key) {
    const dict = translations[this.currentLang] || translations.es;
    return dict[key] || translations.es[key] || key;
  }

  setLanguage(lang) {
    if (!this.supported.includes(lang)) return;
    this.currentLang = lang;
    localStorage.setItem('vartool_lang', lang);
    document.documentElement.lang = lang;

    // Actualizar URL sin recargar para SEO amigabilidad
    const url = new URL(window.location.href);
    url.searchParams.set('lang', lang);
    window.history.replaceState({}, '', url.toString());

    this.applyDomTranslations();
    this.listeners.forEach((cb) => cb(lang));
  }

  onChange(cb) {
    this.listeners.push(cb);
  }

  applyDomTranslations() {
    document.documentElement.lang = this.currentLang;
    document.title = this.t('metaTitle');

    const metaDesc = document.querySelector('meta[name="description"]');
    if (metaDesc) {
      metaDesc.setAttribute('content', this.t('metaDesc'));
    }

    document.querySelectorAll('[data-i18n]').forEach((el) => {
      const key = el.getAttribute('data-i18n');
      el.textContent = this.t(key);
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
      const key = el.getAttribute('data-i18n-placeholder');
      el.setAttribute('placeholder', this.t(key));
    });

    document.querySelectorAll('[data-lang-switch]').forEach((btn) => {
      const isCurrent = btn.getAttribute('data-lang-switch') === this.currentLang;
      btn.classList.toggle('active', isCurrent);
      btn.setAttribute('aria-pressed', String(isCurrent));
    });
  }
}

export const i18n = new I18nManager();
